    ALTER TABLE MEDICINE ADD manufactureDate DATE NULL;

-- VITAL_SIGN
IF COL_LENGTH('VITAL_SIGN','heartRate') IS NULL
    ALTER TABLE VITAL_SIGN ADD heartRate INT NULL;

-- MEDICAL_VISIT
IF COL_LENGTH('MEDICAL_VISIT','visitTime') IS NULL
    ALTER TABLE MEDICAL_VISIT ADD visitTime DATETIME2 NOT NULL
        CONSTRAINT DF_VISIT_time DEFAULT SYSDATETIME();
IF COL_LENGTH('MEDICAL_VISIT','petID') IS NULL
    ALTER TABLE MEDICAL_VISIT ADD petID INT NULL;
GO

UPDATE v SET v.petID = r.petID
FROM MEDICAL_VISIT v JOIN MEDICAL_RECORD r ON r.recordID = v.recordID
WHERE v.petID IS NULL;
GO

ALTER TABLE MEDICAL_VISIT ALTER COLUMN petID INT NOT NULL;
IF NOT EXISTS (SELECT 1 FROM sys.foreign_keys WHERE name = 'FK_VISIT_PETS')
    ALTER TABLE MEDICAL_VISIT ADD CONSTRAINT FK_VISIT_PETS
        FOREIGN KEY (petID) REFERENCES PETS(petID);
GO

-- VACCINATION
IF OBJECT_ID('VACCINATION') IS NULL
CREATE TABLE VACCINATION (
    vaccinationID     INT IDENTITY(1,1) CONSTRAINT PK_VACCINATION PRIMARY KEY,
    visitID           INT  NOT NULL CONSTRAINT FK_VACCINATION_VISIT
                          FOREIGN KEY REFERENCES MEDICAL_VISIT(visitID),
    vaccinID          INT  NOT NULL CONSTRAINT FK_VACCINATION_VACCINE
                          FOREIGN KEY REFERENCES VACCINE(vaccinID),
    injectionDate     DATE NOT NULL,
    nextInjectionDate DATE NULL,
    CONSTRAINT UQ_VACCINATION UNIQUE (visitID, vaccinID)
);
GO

-- Chuyển dữ liệu tiêm cũ (MEDICAL_VISIT.vaccinID) sang bảng mới
INSERT INTO VACCINATION (visitID, vaccinID, injectionDate, nextInjectionDate)
SELECT v.visitID, v.vaccinID, CAST(v.visitTime AS DATE),
       DATEADD(DAY, vc.rcmInterval, CAST(v.visitTime AS DATE))
FROM MEDICAL_VISIT v JOIN VACCINE vc ON vc.vaccinID = v.vaccinID
WHERE v.vaccinID IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM VACCINATION x
                  WHERE x.visitID = v.visitID AND x.vaccinID = v.vaccinID);
GO
